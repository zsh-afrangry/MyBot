// Build the shared default implementations and stable CLI entrypoints.
// Boundary: local TypeScript build and ignored dist writes; no API, DB, or service calls.
// Evidence: docs/verification/capability-decoupling-2026-10-20/README.md
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';

const backend = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const result = spawnSync('npm', ['run', 'build'], {
  cwd: path.join(backend, 'packages/personal-domains'), stdio: 'inherit',
});
if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status ?? 1);

for (const [plugin, entry] of [
  ['personal-weather', 'cli'],
  ['personal-weather', 'reminder-cli'],
  ['personal-reminders', 'reminder-cli'],
]) {
  const directory = path.join(backend, 'plugins', plugin, 'dist');
  // Old weather dist contained the entire former container. Remove generated
  // leftovers before retaining only its two compatibility entrypoints.
  if (plugin === 'personal-weather' && entry === 'cli') fs.rmSync(directory, {recursive: true, force: true});
  fs.mkdirSync(directory, {recursive: true});
  fs.writeFileSync(path.join(directory, entry + '.js'),
    `// Generated by chatbot/scripts/build-personal-plugins.mjs; no business logic.\n` +
    `import {pathToFileURL} from 'node:url';\n` +
    `import {main} from '../../../packages/personal-domains/dist/${entry}.js';\n` +
    `export {main};\n` +
    `if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) process.exitCode = await main();\n`);
}
